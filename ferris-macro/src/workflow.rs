//! Workflow macro.
//!
//! `#[workflow(...)]` emits the annotated item plus:
//! - a `register_workflow()` associated function that installs the definition
//!   into the process-wide [`ferris_document::global_workflow_engine`];
//! - a free `register_<snake_case>_workflow()` helper.
//!
//! Conditions are limited to a safe equality form (`field == number|"str"|true`),
//! never evaluated code.

use crate::WorkflowArgs;
use crate::util::{parse_condition, to_snake_case};
use proc_macro2::TokenStream;
use quote::quote;
use syn::{Error, ItemStruct};

pub fn expand(args: WorkflowArgs, input: ItemStruct) -> Result<TokenStream, Error> {
    let struct_name = &input.ident;
    let doctype = args
        .doctype
        .clone()
        .ok_or_else(|| Error::new_spanned(struct_name, "workflow: `doctype` is required"))?;
    let name = args
        .name
        .clone()
        .unwrap_or_else(|| format!("{doctype} Workflow"));
    let initial_state = args.initial_state.clone().unwrap_or_else(|| {
        args.states
            .first()
            .map(|s| s.name.clone())
            .unwrap_or_else(|| "Draft".to_string())
    });

    let states = args
        .states
        .iter()
        .map(|s| {
            let state = &s.name;
            let label = if s.label.is_empty() {
                quote!(None)
            } else {
                let label = &s.label;
                quote!(Some(#label.to_string()))
            };
            let style = style_token(&s.style);
            let doc_status = match s.doc_status.as_str() {
                "submitted" => quote!(ferris_core::DocStatus::Submitted),
                "cancelled" => quote!(ferris_core::DocStatus::Cancelled),
                _ => quote!(ferris_core::DocStatus::Draft),
            };
            let allow_edit = s.allow_edit.iter().map(|r| quote!(#r.to_string()));
            let allowed_actions = s.allowed_actions.iter().map(|a| quote!(#a.to_string()));
            let auto_assign = match &s.auto_assign {
                Some(value) => quote!(Some(#value.to_string())),
                None => quote!(None),
            };
            quote! {
                ferris_document::WorkflowState {
                    state: #state.to_string(),
                    label: #label,
                    style: #style,
                    doc_status: #doc_status,
                    allow_edit: vec![#(#allow_edit),*],
                    allowed_actions: vec![#(#allowed_actions),*],
                    auto_assign: #auto_assign,
                }
            }
        })
        .collect::<Vec<_>>();

    let transitions = args
        .transitions
        .iter()
        .map(|t| -> Result<TokenStream, Error> {
            let action = &t.action;
            let from_state = &t.from_state;
            let to_state = &t.to_state;
            let name = if t.name.is_empty() {
                quote!(None)
            } else {
                let name = &t.name;
                quote!(Some(#name.to_string()))
            };
            let allowed_roles = t.allowed_roles.iter().map(|r| quote!(#r.to_string()));
            let required_fields = t.required_fields.iter().map(|f| quote!(#f.to_string()));
            let notify = t.notify;
            let condition = match &t.condition {
                Some(expr) => {
                    let (field, value) = parse_condition(expr, "workflow", struct_name.span())?;
                    quote!(Some(ferris_document::WorkflowCondition {
                        field: #field.to_string(),
                        equals: #value,
                    }))
                }
                None => quote!(None),
            };
            Ok(quote! {
                ferris_document::WorkflowTransition {
                    name: #name,
                    action: #action.to_string(),
                    from_state: #from_state.to_string(),
                    to_state: #to_state.to_string(),
                    allowed_roles: vec![#(#allowed_roles),*],
                    condition: #condition,
                    required_fields: vec![#(#required_fields),*],
                    notify: #notify,
                }
            })
        })
        .collect::<Result<Vec<_>, Error>>()?;

    let register_fn = syn::Ident::new(
        &format!(
            "register_{}_workflow",
            to_snake_case(&struct_name.to_string())
        ),
        struct_name.span(),
    );

    Ok(quote! {
        #input

        /// Registration helper generated by `#[workflow]`.
        pub fn #register_fn() -> ferris_core::Result<()> {
            let workflow = ferris_document::Workflow {
                name: #name.to_string(),
                doctype: #doctype.to_string(),
                initial_state: #initial_state.to_string(),
                states: vec![#(#states),*],
                transitions: vec![#(#transitions),*],
            };
            ferris_document::global_workflow_engine().register(workflow)
        }

        impl #struct_name {
            /// Register this workflow in the process-wide engine.
            pub fn register_workflow() -> ferris_core::Result<()> {
                #register_fn()
            }
        }
    })
}

/// Map a style string from the attribute to a `StateStyle` variant.
fn style_token(style: &str) -> TokenStream {
    let variant = match style.to_ascii_lowercase().as_str() {
        "primary" => "Primary",
        "info" => "Info",
        "success" => "Success",
        "warning" => "Warning",
        "danger" => "Danger",
        "inverse" => "Inverse",
        _ => "Default",
    };
    let ident = syn::Ident::new(variant, proc_macro2::Span::call_site());
    quote!(ferris_document::StateStyle::#ident)
}
